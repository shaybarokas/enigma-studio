/** A list item's icon in a disc of the accent colour. */
export const ItemIcon: React.FC<{
  name?: string;
  size: number;
  color: string;
  ink: string;
  progress?: number;
}> = ({ name, size, color, ink, progress = 1 }) => {
  const Icon = ICONS[(name ?? "check") as IconKey] ?? Check;
  return (
    <div
      style={{
        flex: "none",
        width: size,
        height: size,
        borderRadius: "50%",
        background: color,
        display: "grid",
        placeItems: "center",
        boxShadow: `0 0 ${size * 0.5}px ${color}66`,
        transform: `scale(${0.6 + 0.4 * progress})`,
      }}
    >
      <Icon size={size * 0.56} color={ink} strokeWidth={2.4} />
    </div>
  );
};
